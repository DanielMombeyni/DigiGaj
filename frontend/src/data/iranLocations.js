export const IRAN_PROVINCES = RAW.map(([name, cities]) => ({
  name,
  cities: [...cities].sort((a, b) => a.localeCompare(b, 'fa')),
}))

const BY_PROVINCE = new Map(IRAN_PROVINCES.map((row) => [row.name, row.cities]))

export function citiesOf(province) {
  return BY_PROVINCE.get(province) || []
}
